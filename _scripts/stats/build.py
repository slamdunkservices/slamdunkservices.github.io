#!/usr/bin/env python3
"""Generate the stats pages under stats/ from the league data mirrors.

  /Users/jim/Code/jobs/mlb/.venv/bin/python _scripts/stats/build.py        # all leagues
  ... build.py nba wnba mlb                                                  # a subset

Reads (roots from ~/.<league>_jobs.env, see agents.md):
  NBA/WNBA  02_curated/<l>_first_events, <l>_tip_events, boxscores (starters), game logs (dates, home/away),
            teams, player names
  MLB       01_raw/linescores (runs by inning), schedules (teams, game type), probables (listed starters)

Writes one .qmd per team plus a leaders page per league, and _scripts/stats/cards.tsv (share-card rows for
_scripts/og-cards/build.sh). Every generated file carries a marker comment right after its frontmatter; edit the templates here, not
the output. The hub page stats/index.qmd is hand-written and not touched.
"""
import datetime as dt
import os
import re
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "stats"
CARDS = ROOT / "_scripts" / "stats" / "cards.tsv"
TODAY = dt.date.today()
MARK = "<!-- generated by _scripts/stats/build.py on %s; edit the script, not this file -->" % TODAY.isoformat()
MIN_GAMES_FOR_SEASON = 100   # a basketball season counts as "current" once this many games are in the data
NBA_CUTOFF = 150             # league-wide leaders page: players with at least this many games across the window


def data_root(league):
    env = Path.home() / (".%s_jobs.env" % league)
    key = "%s_DATA_ROOT" % league.upper()
    if env.exists():
        for line in env.read_text().splitlines():
            line = line.strip().removeprefix("export ").strip()
            if line.startswith(key + "="):
                return Path(line.split("=", 1)[1].strip().strip('"'))
    return Path.home() / "Desktop" / "files" / ("sdbs_%s" % league)


def slugify(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def poss(name):
    """Possessive: Lakers' but Heat's, Magic's, Jazz's."""
    return name + ("'" if name.endswith("s") else "'s")


def pct(n, d, digits=0):
    if not d:
        return "–"
    v = 100.0 * n / d
    return ("%%.%df%%%%" % digits) % v


def fmt_int(n):
    return "{:,}".format(int(n))


def yaml_str(s):
    return '"' + str(s).replace('"', "'") + '"'


def faq(question, answer):
    return "::: {.faq-item}\n### %s\n\n%s\n:::\n" % (question, answer)


def md_table(headers, rows, align=None):
    align = align or ["---"] + ["---:"] * (len(headers) - 1)
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join(align) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(x) for x in r) + " |")
    return "\n".join(out)


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    print("wrote", path.relative_to(ROOT))


METHOD_LABEL = {"layup": "Layup", "dunk": "Dunk", "other_fg": "Other 2-pointer (jumper, hook, tip)",
                "three_point": "3-pointer", "free_throw": "Free throw"}

card_rows = []


# --------------------------------------------------------------------------- basketball

class Hoops:
    """One basketball league's tables, normalized so NBA and WNBA share the page code."""

    def __init__(self, league):
        self.league = league
        self.L = league.upper()
        self.root = data_root(league)
        cur = self.root / "02_curated"
        p = {"nba": dict(fe="nba_first_events/current.csv", tip="nba_tip_events/current.csv",
                         box="nba_boxscores/current.csv.gz", logs="nba_gamelogs/current.csv.gz",
                         teams="nba_teams/current.csv", players="nba_common_all_players/current.csv"),
             "wnba": dict(fe="wnba_first_events/current.csv", tip="wnba_tip_events/current.csv",
                          box="boxscore/current.csv", logs="player_game_logs/current.csv.gz",
                          teams="teams/current.csv", players=None)}[league]
        norm = lambda s: s.astype(str).str.strip().str.lstrip("0")

        fe = pd.read_csv(cur / p["fe"], dtype=str)
        fe["game_id"] = norm(fe.game_id)
        fe["gametime"] = pd.to_numeric(fe.gametime, errors="coerce")
        fe = fe[fe.shot_type != "overall"]
        self.fe = fe

        tip = pd.read_csv(cur / p["tip"], dtype=str)
        tip["game_id"] = norm(tip.game_id)
        tip = tip[tip.opening_tip.astype(str).str.upper() == "TRUE"].drop_duplicates("game_id")
        self.tip = tip[["game_id", "player1_id", "player1_team", "player2_id", "player2_team",
                        "tip_win_player_id", "tip_win_team_id"]]

        box = pd.read_csv(cur / p["box"], dtype=str, usecols=["GAME_ID", "TEAM_ID", "PLAYER_ID", "PLAYER_NAME", "START_POSITION"])
        box["game_id"] = norm(box.GAME_ID)
        box["team_id"] = norm(box.TEAM_ID)
        box["player_id"] = norm(box.PLAYER_ID)
        self.box = box
        self.starts = box[box.START_POSITION.fillna("").str.strip() != ""][["game_id", "team_id", "player_id"]].drop_duplicates()

        logs = pd.read_csv(cur / p["logs"], dtype=str, usecols=["GAME_ID", "GAME_DATE", "MATCHUP", "TEAM_ID", "TEAM_ABBREVIATION"])
        logs["game_id"] = norm(logs.GAME_ID)
        logs["team_id"] = logs.TEAM_ID.astype(str).str.replace(r"\.0$", "", regex=True).str.lstrip("0")
        logs = logs.drop_duplicates(["game_id", "team_id"])
        logs["home"] = logs.MATCHUP.str.contains("vs.", regex=False)
        logs["date"] = pd.to_datetime(logs.GAME_DATE.str[:10], errors="coerce")
        self.logs = logs
        home = logs[logs.home].drop_duplicates("game_id").set_index("game_id").team_id
        away = logs[~logs.home].drop_duplicates("game_id").set_index("game_id").team_id
        date = logs.groupby("game_id").date.min()
        games = pd.DataFrame({"home_team_id": home, "away_team_id": away, "date": date}).reset_index()
        games = games.dropna(subset=["home_team_id", "away_team_id"])
        games = games[games.home_team_id != games.away_team_id]
        games["season"] = games.game_id.map(self.season_of)
        games["phase"] = games.game_id.map(self.phase_of)
        self.games = games[games.phase.notna()]

        teams = pd.read_csv(cur / p["teams"], dtype=str)
        teams["team_id"] = norm(teams.TEAM_ID)
        self.teams = teams.set_index("team_id")[["TEAM_FULL_NAME", "TEAM_ABBREVIATION", "TEAM_NAME"]]

        names = box.drop_duplicates("player_id").set_index("player_id").PLAYER_NAME.to_dict()
        if p["players"]:
            cp = pd.read_csv(cur / p["players"], dtype=str)
            names.update(dict(zip(norm(cp.PERSON_ID), cp.DISPLAY_FIRST_LAST)))
        self.names = names

    # game id conventions: NBA "22500001" = type 2, season 25 -> 2025-26; WNBA "1022600001" = type at [2], season at [3:5]
    def season_of(self, gid):
        if self.league == "nba":
            yy = int(gid[1:3])
            return "20%02d-%02d" % (yy, yy + 1)
        return "20" + gid[3:5]

    def phase_of(self, gid):
        t = gid[0] if self.league == "nba" else gid[2]
        return {"2": "Regular season", "4": "Playoffs", "5": "Play-in", "6": "Cup final"}.get(t)

    def first(self, event, group):
        """Earliest `event` per game (group=game) or per game and team (group=team); shot_type is the method."""
        d = self.fe[(self.fe.event == event) & (self.fe.group == group)].dropna(subset=["gametime"])
        keys = ["game_id"] + (["team_id"] if group == "team" else [])
        d = d.sort_values(keys + ["gametime"]).drop_duplicates(keys)
        d["team_id"] = d.team_id.astype(str).str.lstrip("0")
        d["player_id"] = d.player_id.astype(str).str.lstrip("0")
        return d[keys + [c for c in ["player_id", "team_id", "shot_type"] if c not in keys]]

    def seasons(self):
        counts = self.games.groupby("season").game_id.nunique()
        ok = counts[counts >= MIN_GAMES_FOR_SEASON].index.tolist()
        return sorted(ok)

    def name(self, pid):
        return self.names.get(str(pid).lstrip("0"), "Player %s" % pid)

    def team(self, tid):
        tid = str(tid).lstrip("0")
        if tid in self.teams.index:
            r = self.teams.loc[tid]
            return r.TEAM_FULL_NAME, r.TEAM_ABBREVIATION, r.TEAM_NAME
        return "Team %s" % tid, tid, "Team %s" % tid

    def season_frame(self, season):
        g = self.games[self.games.season == season]
        ids = set(g.game_id)
        fg = self.first("fgm", "game");   fg = fg[fg.game_id.isin(ids)]
        ft = self.first("fgm", "team");   ft = ft[ft.game_id.isin(ids)]
        pg = self.first("points", "game"); pg = pg[pg.game_id.isin(ids)]
        st = self.starts[self.starts.game_id.isin(ids)]
        tp = self.tip[self.tip.game_id.isin(ids)].copy()
        for c in ["tip_win_player_id", "tip_win_team_id", "player1_id", "player2_id", "player1_team", "player2_team"]:
            tp[c] = tp[c].astype(str).str.lstrip("0")
        return dict(games=g, fg=fg, ft=ft, pg=pg, starts=st, tip=tp)

    def player_table(self, f, team_id=None):
        """Per player (and team): starts, first baskets for team, first baskets of the game."""
        st = f["starts"]; ft = f["ft"]; fg = f["fg"]
        if team_id:
            st = st[st.team_id == team_id]; ft = ft[ft.team_id == team_id]; fg = fg[fg.team_id == team_id]
        starts = st.groupby(["player_id", "team_id"]).size().rename("starts")
        first_team = ft.groupby(["player_id", "team_id"]).size().rename("first_team")
        first_game = fg.groupby(["player_id", "team_id"]).size().rename("first_game")
        t = pd.concat([starts, first_team, first_game], axis=1).fillna(0).astype(int).reset_index()
        t["rate_team"] = np.where(t.starts > 0, t.first_team / t.starts.replace(0, np.nan), np.nan)
        t["rate_game"] = np.where(t.starts > 0, t.first_game / t.starts.replace(0, np.nan), np.nan)
        t["player"] = t.player_id.map(self.name)
        t["abbr"] = t.team_id.map(lambda x: self.team(x)[1])
        return t

    def team_table(self, f):
        g = f["games"]; fg = f["fg"]; tp = f["tip"]
        rows = []
        for tid in sorted(set(g.home_team_id) | set(g.away_team_id)):
            mine = g[(g.home_team_id == tid) | (g.away_team_id == tid)]
            first = fg[fg.game_id.isin(mine.game_id)]
            scored = first[first.team_id == tid]
            home_ids = set(mine[mine.home_team_id == tid].game_id)
            tips = tp[tp.game_id.isin(mine.game_id) & ((tp.player1_team == tid) | (tp.player2_team == tid))]
            rows.append(dict(team_id=tid, games=len(mine), with_first=len(first), scored_first=len(scored),
                             home_games=len(home_ids), home_first=len(scored[scored.game_id.isin(home_ids)]),
                             home_with=len(first[first.game_id.isin(home_ids)]),
                             away_games=len(mine) - len(home_ids),
                             away_first=len(scored[~scored.game_id.isin(home_ids)]),
                             away_with=len(first[~first.game_id.isin(home_ids)]),
                             tips=len(tips), tip_wins=int((tips.tip_win_team_id == tid).sum())))
        t = pd.DataFrame(rows)
        t["name"] = t.team_id.map(lambda x: self.team(x)[0])
        t["abbr"] = t.team_id.map(lambda x: self.team(x)[1])
        return t

    # ------------------------------------------------------------------ pages

    def market_link(self):
        return "../../%s/first-basket-picks.qmd" % self.league, "../%s/first-basket-picks.qmd" % self.league

    def build(self):
        seasons = self.seasons()
        if not seasons:
            sys.exit("%s: no season with %d+ games" % (self.L, MIN_GAMES_FOR_SEASON))
        cur = seasons[-1]
        prev = seasons[-2] if len(seasons) > 1 else None
        f = self.season_frame(cur)
        fp = self.season_frame(prev) if prev else None
        print("%s: current season %s (%d games), previous %s" % (self.L, cur, len(f["games"]), prev))
        teams = self.team_table(f)
        players = self.player_table(f)
        self.leaders_page(cur, prev, f, fp, teams, players)
        for tid in teams.team_id:
            self.team_page(tid, cur, prev, f, fp, teams, players)

    def phases_note(self, f):
        ph = f["games"].phase.value_counts()
        parts = ["%s %s" % (fmt_int(n), p.lower()) for p, n in ph.items()]
        return ", ".join(parts)

    def leaders_page(self, cur, prev, f, fp, teams, players):
        L = self.L
        n_games = len(f["games"]); n_first = len(f["fg"])
        lead = players.sort_values(["first_game", "first_team"], ascending=False)
        lead = lead[lead.first_game > 0].head(25)
        rate = players[players.starts >= (30 if self.league == "nba" else 15)].sort_values("rate_team", ascending=False).head(25)
        top = lead.iloc[0]
        method = f["fg"].shot_type.map(METHOD_LABEL).value_counts()
        ft_first = f["pg"].merge(f["fg"], on="game_id", suffixes=("_pts", "_fg"))
        diff = int((ft_first.player_id_pts != ft_first.player_id_fg).sum())
        tt = teams.sort_values("scored_first", ascending=False)

        min_starts = 30 if self.league == "nba" else 15
        desc = ("%s first basket stats for %s: %s led the league with %d first baskets of the game, the players who score "
                "first most often per start, how often each team scores first and wins the tipoff, and how first baskets are "
                "scored, from play-by-play data." % (L, cur, top["player"], top.first_game))
        title = "%s First Basket Stats %s: Leaders, Team Rates and Tipoffs" % (L, cur)
        body = ["---", "title: %s" % yaml_str(title), "pagetitle: %s" % yaml_str("%s First Basket Stats %s: Who Scores First" % (L, cur)),
                "description: %s" % yaml_str(desc), "date-modified: %s" % TODAY.isoformat(),
                "image: /images/og/stats-%s-first-basket-leaders.png" % self.league,
                "image-alt: %s" % yaml_str("%s first basket leaders %s: %s scored first in %d games" % (L, cur, top["player"], top.first_game)),
                "---", MARK, ""]
        body.append(
            "Who scores first in the %s? This page counts the first field goal of every %s game in %s (%s) from the play-by-play, "
            "then breaks it down by player, team and scoring method. These are the same labels our [first basket models](%s) "
            "learn from; the models add tonight's lineups, the opponent and the price at every sportsbook."
            % (L, L, cur, self.phases_note(f), self.market_link()[1]))
        body.append("\n## Most first baskets of the game, %s\n" % cur)
        body.append("Starts are games started. The team column counts the first basket *for that player's team*, which is a separate "
                    "market with two winners per game.\n")
        body.append(md_table(["Player", "Team", "Starts", "First basket of game", "Rate", "First basket for team", "Rate"],
                             [(r.player, r.abbr, r.starts, r.first_game, pct(r.first_game, r.starts), r.first_team, pct(r.first_team, r.starts)) for r in lead.itertuples()],
                             ["---", "---", "---:", "---:", "---:", "---:", "---:"]))
        body.append("\n## Highest first basket rate for their team (%d+ starts)\n" % min_starts)
        body.append(md_table(["Player", "Team", "Starts", "First basket for team", "Rate", "First basket of game", "Rate"],
                             [(r.player, r.abbr, r.starts, r.first_team, pct(r.first_team, r.starts), r.first_game, pct(r.first_game, r.starts)) for r in rate.itertuples()],
                             ["---", "---", "---:", "---:", "---:", "---:", "---:"]))
        body.append("\n## Which teams score first, and who wins the tipoff\n")
        body.append("Scored first is the share of games in which the team made the game's first field goal. Tipoff is the opening jump ball.\n")
        body.append(md_table(["Team", "Games", "Scored first", "Rate", "Home", "Away", "Tipoff wins", "Rate"],
                             [("[%s](%s/%s.qmd)" % (r.name, self.league, slugify(r.name)), r.games, r.scored_first, pct(r.scored_first, r.with_first),
                               pct(r.home_first, r.home_with), pct(r.away_first, r.away_with), "%d/%d" % (r.tip_wins, r.tips), pct(r.tip_wins, r.tips)) for r in tt.itertuples()],
                             ["---", "---:", "---:", "---:", "---:", "---:", "---:", "---:"]))
        body.append("\n## How first baskets are scored\n")
        body.append(md_table(["Method", "First baskets", "Share"], [(m, n, pct(n, n_first)) for m, n in method.items()]))
        body.append("\nIn %s of %s games (%s) the game's first points came from a different player than its first field goal, usually "
                    "a free throw. That is the difference between a *first points* market and a *first field goal* market; our "
                    "[first basket guide](../guides/what-is-a-first-basket-bet.qmd) explains which books use which."
                    % (fmt_int(diff), fmt_int(len(ft_first)), pct(diff, len(ft_first))))
        if fp is not None:
            pl = self.player_table(fp).sort_values("first_game", ascending=False).head(10)
            body.append("\n## %s leaders\n" % prev)
            body.append(md_table(["Player", "Team", "Starts", "First basket of game", "Rate", "First basket for team", "Rate"],
                                 [(r.player, r.abbr, r.starts, r.first_game, pct(r.first_game, r.starts), r.first_team, pct(r.first_team, r.starts)) for r in pl.itertuples()],
                                 ["---", "---", "---:", "---:", "---:", "---:", "---:"]))
        body.append("\n## Team pages\n")
        body.append(" · ".join("[%s](%s/%s.qmd)" % (r.name, self.league, slugify(r.name)) for r in teams.sort_values("name").itertuples()))
        body.append("")
        body.append(faq("Who scored the most first baskets in the %s in %s?" % (L, cur),
                        "%s, with %d first baskets of the game in %d starts (%s). %s was second with %d."
                        % (top["player"], top.first_game, top.starts, pct(top.first_game, top.starts), lead.iloc[1]["player"], lead.iloc[1].first_game)))
        body.append(faq("How often does the home team score first in the %s?" % L,
                        "In %s, the home team made the first field goal in %s of games." % (cur, pct(teams.home_first.sum(), teams.home_with.sum()))))
        body.append(faq("How often does the team that wins the tipoff score first?",
                        self.tip_vs_first(f)))
        body.append(faq("Are these the picks?",
                        "No. This page is history. The picks come from our models, which combine this history with tonight's starting "
                        "lineup, the opponent, pace and the price at each book, and post to Discord when a price is better than the "
                        "projection. See [%s first basket picks](%s)." % (L, self.market_link()[1])))
        body.append("\n[Subscribe — first month free](https://sharpduel.com/slam_dunk_bets){.btn .btn-primary .btn-lg role=\"button\"}\n")
        body.append("Source: %s play-by-play and box scores, %s. Updated %s. Back to [all stats](index.qmd)." % (L, cur, TODAY.strftime("%B %-d, %Y")))
        write(OUT / ("%s-first-basket-leaders.qmd" % self.league), "\n".join(body) + "\n")
        card_rows.append(("stats-%s-first-basket-leaders" % self.league, "%s First Basket Stats %s" % (L, cur),
                          "%s: %d first baskets" % (top["player"], top.first_game),
                          "Leaders, team rates and tipoffs for every %s game" % L, "From play-by-play · Updated %s" % TODAY.strftime("%b %-d, %Y")))

    def tip_vs_first(self, f):
        m = f["tip"].merge(f["fg"], on="game_id")
        n = len(m); w = int((m.tip_win_team_id == m.team_id).sum())
        if not n:
            return "Not enough tipoff data this season."
        return ("In %s of %s games with a recorded opening tip (%s), the team that won it also made the first field goal. "
                "Winning the ball helps, but a missed first shot hands the chance to the other side." % (fmt_int(w), fmt_int(n), pct(w, n)))

    def team_page(self, tid, cur, prev, f, fp, teams, players):
        L = self.L
        full, abbr, nick = self.team(tid)
        slug = slugify(full)
        tr = teams[teams.team_id == tid].iloc[0]
        pt = players[(players.team_id == tid) & ((players.first_team > 0) | (players.starts >= 10))].sort_values(
            ["first_team", "first_game", "starts"], ascending=False)
        if pt.empty:
            return
        top = pt.iloc[0]
        second = pt.iloc[1] if len(pt) > 1 else None
        fg_team = f["ft"][f["ft"].team_id == tid]
        method = fg_team.shot_type.map(METHOD_LABEL).value_counts()
        tips = f["tip"][(f["tip"].player1_team == tid) | (f["tip"].player2_team == tid)].copy()
        tips["jumper"] = np.where(tips.player1_team == tid, tips.player1_id, tips.player2_id)
        tips["won"] = tips.tip_win_team_id == tid
        jt = tips.groupby("jumper").agg(tips=("won", "size"), won=("won", "sum")).sort_values("tips", ascending=False)
        ph = f["games"]; mine = ph[(ph.home_team_id == tid) | (ph.away_team_id == tid)]
        by_phase = []
        for phase, g in mine.groupby("phase"):
            first = f["fg"][f["fg"].game_id.isin(g.game_id)]
            by_phase.append((phase, len(g), int((first.team_id == tid).sum()), len(first)))
        order = {"Regular season": 0, "Play-in": 1, "Playoffs": 2, "Cup final": 3}
        by_phase.sort(key=lambda x: order.get(x[0], 9))

        title = "%s First Basket Stats %s: Who Scores First" % (full, cur)
        desc = ("Who scores the first basket for the %s: %s led with %d first baskets for the team in %d starts (%s) in %s. "
                "How often the %s score first at home and away, their tipoff record, and how their first baskets are scored."
                % (full, top["player"], top.first_team, top.starts, pct(top.first_team, top.starts), cur, nick))
        body = ["---", "title: %s" % yaml_str(title), "pagetitle: %s" % yaml_str("%s First Basket Stats %s: Who Scores First" % (nick if self.league == "nba" else full, cur)),
                "description: %s" % yaml_str(desc), "date-modified: %s" % TODAY.isoformat(),
                "image: /images/og/stats-%s-%s.png" % (self.league, slug),
                "image-alt: %s" % yaml_str("%s first basket stats %s: %s scored first for the team %d times" % (full, cur, top["player"], top.first_team)),
                "---", MARK, ""]
        lede = ("%s scored the %s first basket more than anyone in %s: %d times in %d starts, or %s of the games they started."
                % (top["player"], poss(nick), cur, top.first_team, top.starts, pct(top.first_team, top.starts)))
        if second is not None:
            lede += " %s was next with %d." % (second["player"], second.first_team)
