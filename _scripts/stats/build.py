def nickname(name):
    for c in sorted(MLB_CITIES, key=len, reverse=True):
        if name.startswith(c + " ") and name != c:
            return name[len(c) + 1:]
    return name


class Baseball:
    def __init__(self):
        self.root = data_root("mlb")
        raw = self.root / "01_raw"
        seasons = sorted(int(p.stem) for p in (raw / "linescores").glob("*.csv"))
        self.seasons = seasons
        frames = []
        for s in seasons:
            ls = pd.read_csv(raw / "linescores" / ("%d.csv" % s))
            sc = pd.read_csv(raw / "schedules" / ("%d.csv" % s), low_memory=False)
            sc = sc[(sc.game_type == "R") & sc.status_detailed_state.isin(["Final", "Completed Early"])]
            sc = sc[["game_pk", "official_date", "teams_home_team_id", "teams_home_team_name", "teams_away_team_id", "teams_away_team_name"]].drop_duplicates("game_pk")
            i1 = ls[ls.inning == 1].drop_duplicates("game_pk").merge(sc, on="game_pk")
            i1["season"] = s
            frames.append(i1)
        g = pd.concat(frames, ignore_index=True)
        g["date"] = pd.to_datetime(g.official_date)
        g["month"] = g.date.dt.strftime("%B")
        g["nrfi"] = (g.away_runs + g.home_runs) == 0
        self.games = g
        cur = max(s for s in seasons if (g.season == s).sum() >= 200)
        self.cur = cur
        prob = pd.read_csv(raw / "probables" / ("%d.csv" % cur))
        prob = prob.drop_duplicates(["game_pk", "team_id"])
        self.prob = prob[["game_pk", "team_id", "id", "fullName"]].rename(columns={"id": "pitcher_id", "fullName": "pitcher"})

    def team_games(self, tid, season):
        g = self.games[self.games.season == season]
        g = g[(g.teams_home_team_id == tid) | (g.teams_away_team_id == tid)].copy()
        g["home"] = g.teams_home_team_id == tid
        g["scored"] = np.where(g.home, g.home_runs, g.away_runs)
        g["allowed"] = np.where(g.home, g.away_runs, g.home_runs)
        return g

    def pitchers(self, season, tid=None):
        g = self.games[self.games.season == season]
        m = g.merge(self.prob, on="game_pk")
        m["home"] = m.team_id == m.teams_home_team_id
        m["allowed"] = np.where(m.home, m.away_runs, m.home_runs)
        m["team"] = np.where(m.home, m.teams_home_team_name, m.teams_away_team_name)
        if tid is not None:
            m = m[m.team_id == tid]
        t = m.groupby(["pitcher_id", "pitcher"]).agg(starts=("game_pk", "size"), scoreless=("allowed", lambda x: int((x == 0).sum())),
                                                     runs=("allowed", "sum"), team=("team", lambda x: " / ".join(sorted(set(x))))).reset_index()
        t["rate"] = t.scoreless / t.starts
        return t

    def team_list(self, season):
        g = self.games[self.games.season == season]
        ids = pd.concat([g[["teams_home_team_id", "teams_home_team_name"]].rename(columns={"teams_home_team_id": "id", "teams_home_team_name": "name"}),
                         g[["teams_away_team_id", "teams_away_team_name"]].rename(columns={"teams_away_team_id": "id", "teams_away_team_name": "name"})])
        return ids.drop_duplicates("id").sort_values("name")

    def team_row(self, tid, season):
        g = self.team_games(tid, season)
        return dict(games=len(g), nrfi=int(g.nrfi.sum()), home_games=int(g.home.sum()), home_nrfi=int(g[g.home].nrfi.sum()),
                    away_games=int((~g.home).sum()), away_nrfi=int(g[~g.home].nrfi.sum()),
                    scored=int((g.scored > 0).sum()), allowed=int((g.allowed > 0).sum()),
                    runs_scored=float(g.scored.sum()), runs_allowed=float(g.allowed.sum()))

