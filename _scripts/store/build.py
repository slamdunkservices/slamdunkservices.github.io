# ---------- formatting ----------

def esc(text) -> str:
    return html.escape(str(text), quote=True)


def yaml_str(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


def money(dollars) -> str:
    return "$%s" % format(int(dollars), ",")


def count(n: int) -> str:
    return format(int(n), ",")


def approx(n: int) -> str:
    if n >= 1_000_000:
        return "%.1f million" % (n / 1_000_000)
    if n >= 10_000:
        return "%s,000" % format(round(n / 1000), ",")
    return count(n)


def size(nbytes: int) -> str:
    if nbytes >= 1_048_576:
        return "%.1f MB" % (nbytes / 1_048_576)
    return "%d KB" % max(1, round(nbytes / 1024))


def span(seasons: list[str]) -> str:
    if not seasons:
        return ""
    return seasons[0] if len(seasons) == 1 else "%s to %s" % (seasons[0], seasons[-1])


def plural(n: int, word: str) -> str:
    return "%s %s%s" % (count(n), word, "" if n == 1 else "s")


# ---------- inputs ----------

def sync(source: Path) -> None:
    src = source / "catalog.json"
    if not src.exists():
        sys.exit("no catalog.json in %s; run `python -m datastore_jobs.cli describe` in the jobs repo first" % source)
    STORE.mkdir(exist_ok=True)
    shutil.copyfile(src, STORE / "datasets.json")
    dest = STORE / "samples"
    if dest.exists():
        shutil.rmtree(dest)
    dest.mkdir()
    for path in sorted((source / "samples").glob("*.csv")):
        shutil.copyfile(path, dest / path.name)
    print("synced datasets.json and %d samples from %s" % (len(list(dest.glob("*.csv"))), source))


def load() -> tuple[dict, dict]:
    pricing = tomllib.loads((STORE / "pricing.toml").read_text())
    path = STORE / "datasets.json"
    if not path.exists():
        sys.exit("no _store/datasets.json; run with --sync once the jobs repo has built its catalog")
    return pricing, json.loads(path.read_text())


class League:
    """One league as the pages need it: catalog facts joined to prices."""

    def __init__(self, code: str, pricing: dict, catalog: dict):
        self.code = code
        cfg = pricing["leagues"][code]
        cat = catalog["leagues"][code]
        self.name = cfg["name"]
        self.cadence = cfg.get("cadence", "")
        self.prices = cfg["prices"]
        self.dataset_names = {k: v["name"] for k, v in pricing["datasets"].items()}
        self.blurbs = {k: v["blurb"] for k, v in pricing["datasets"].items()}
        self.datasets = [d for d in cat["datasets"] if d["key"] in self.prices]
        self.all_seasons = sorted({s for d in self.datasets for f in d["files"] for s in f["seasons"]})
        # A pass is on sale only when pricing names the season AND the files for it exist.
        wanted = (cfg.get("current") or "").strip()
        self.current = wanted if wanted in self.all_seasons else None
        self.completed = [s for s in self.all_seasons if s != self.current]

    def seasons_of(self, dataset: dict) -> list[str]:
        return sorted({s for f in dataset["files"] for s in f["seasons"]})

    def completed_of(self, dataset: dict) -> list[str]:
        return [s for s in self.seasons_of(dataset) if s != self.current]

    def rows(self, dataset: dict, season: str) -> int:
        return sum(f["seasons"].get(season, {}).get("rows", 0) for f in dataset["files"])

    def bytes(self, dataset: dict, season: str) -> int:
        return sum(f["seasons"].get(season, {}).get("bytes", 0) for f in dataset["files"])

    def total_rows(self) -> int:
        return sum(self.rows(d, s) for d in self.datasets for s in self.seasons_of(d))

    def file_count(self) -> int:
        return sum(len(f["seasons"]) for d in self.datasets for f in d["files"])

    def label(self, dataset: dict) -> str:
        return self.dataset_names.get(dataset["key"], dataset["title"])

    def page(self, dataset: dict) -> str:
        return "%s-%s" % (self.code, dataset["key"])

    def has_archive(self) -> bool:
        return "archive" in self.prices and len(self.completed) > 1


# ---------- building blocks ----------

def add_button(league: str, dataset: str, season: str, label: str, big: bool = False) -> str:
    return ('<button type="button" class="btn store-add%s" data-store-add data-league="%s" '
            'data-dataset="%s" data-season="%s" data-label="%s">%s</button>'
            % (" store-add-lg" if big else "", esc(league), esc(dataset), esc(season), esc(label), esc(label)))


def raw(block: str) -> str:
    return "```{=html}\n%s\n```\n" % block.strip("\n")


def table(head: list[str], rows: list[list[str]], num: set[int] = frozenset(), cls: str = "table store-table") -> str:
    def cell(tag, i, value):
        return "<%s%s>%s</%s>" % (tag, ' class="num"' if i in num else "", value, tag)
    out = ['<table class="%s">' % cls, "<thead><tr>"]
    out += [cell("th", i, h) for i, h in enumerate(head)]
    out.append("</tr></thead><tbody>")
    for row in rows:
        out.append("<tr>%s</tr>" % "".join(cell("td", i, v) for i, v in enumerate(row)))
    out.append("</tbody></table>")
    return "\n".join(out)


def facts(pairs: list[tuple[str, str]]) -> str:
    items = "".join("<div><dt>%s</dt><dd>%s</dd></div>" % (esc(k), v) for k, v in pairs if v)
    return raw('<dl class="store-facts">%s</dl>' % items)


def frontmatter(title: str, pagetitle: str, description: str, image: str | None = None,
                image_alt: str | None = None, extra: list[str] = ()) -> str:
    lines = ["---", "title: %s" % yaml_str(title), "pagetitle: %s" % yaml_str(pagetitle),
             "description: %s" % yaml_str(description), "date-modified: %s" % TODAY.isoformat()]
    if image:
        lines += ["image: %s" % image, "image-alt: %s" % yaml_str(image_alt or title)]
    lines += list(extra)
    lines += ["---", "", MARK, ""]
    return "\n".join(lines)


def opening_soon(pricing: dict) -> str:
    if pricing["store"].get("api"):
        return ""
    return ("::: {.store-status .store-status-warn}\n"
            "Checkout opens soon. You can browse every dataset, read the column dictionaries and download the "
            "samples now; to buy before the cart is switched on, [email us](mailto:%s).\n:::\n\n"
            % pricing["store"]["support_email"])


def dataset_jsonld(lg: League, dataset: dict, url: str) -> str:
    seasons = lg.seasons_of(dataset)
    first = min((f["seasons"][s].get("first_date") or "" for f in dataset["files"] for s in f["seasons"]
                 if f["seasons"][s].get("first_date")), default="")
    last = max((f["seasons"][s].get("last_date") or "" for f in dataset["files"] for s in f["seasons"]
                if f["seasons"][s].get("last_date")), default="")
    price = lg.prices[dataset["key"]]
    node = {
        "@context": "https://schema.org", "@type": "Dataset", "@id": url + "#dataset",
        "name": "%s %s" % (lg.name, lg.label(dataset)),
        "description": dataset["summary"], "url": url,
        "creator": {"@type": "Organization", "name": "Slam Dunk Bets", "url": SITE + "/"},
        "isAccessibleForFree": False,
        "license": SITE + "/data/help.html#license",
        "keywords": [lg.name, lg.label(dataset).lower(), "CSV", "sports data", "flat file"],
        "variableMeasured": [c["name"] for f in dataset["files"] for c in f["columns"]][:120],
        "distribution": [{"@type": "DataDownload", "encodingFormat": "text/csv", "contentUrl": url}],
        "offers": {"@type": "Offer", "price": str(price["season"]), "priceCurrency": "USD", "url": url,
                   "availability": "https://schema.org/InStock"},
    }
    if first and last:
        node["temporalCoverage"] = "%s/%s" % (first, last)
    elif seasons:
        node["temporalCoverage"] = "%s/%s" % (seasons[0][:4], seasons[-1][:4])
    text = json.dumps(node, ensure_ascii=False).replace("</", "<\\/")
    return raw('<script type="application/ld+json">%s</script>' % text)


def sample_block(lg: League, dataset: dict, spec: dict) -> str:
    rel = spec.get("sample")
    if not rel:
        return ""
    name = Path(rel).name
    path = STORE / "samples" / name
    if not path.exists():
        return ""
    with path.open(newline="", encoding="utf-8") as fh:
        rows = list(csv.reader(fh))
    if len(rows) < 2:
        return ""
    head, body = rows[0], rows[1:1 + SAMPLE_ROWS]
    out = ['<div class="store-sample" tabindex="0" role="region" aria-label="Sample rows"><table class="table">',
           "<thead><tr>%s</tr></thead><tbody>" % "".join("<th>%s</th>" % esc(h) for h in head)]
    for row in body:
        out.append("<tr>%s</tr>" % "".join("<td>%s</td>" % esc(v) for v in row))
    out.append("</tbody></table></div>")
    note = ("First %d rows of the sample, all %d columns; scroll sideways. "
            "[Download the sample CSV](samples/%s) (%s)."
            % (len(body), len(head), name, plural(len(rows) - 1, "row")))
    return raw("\n".join(out)) + "\n" + "[%s]{.store-note}\n" % note


def dictionary(spec: dict) -> str:
    rows = [[esc(c["name"]), esc(c["type"]), esc(c["description"])] for c in spec["columns"]]
    return raw('<div class="store-dict">%s</div>' % table(["Column", "Type", "What it holds"], rows, cls="table"))


