#!/usr/bin/env python3
"""Generate the data store pages under data/ from the catalog and the price list.

    python3 _scripts/store/build.py            # rebuild the pages from _store/
    python3 _scripts/store/build.py --sync     # first refresh _store/datasets.json and _store/samples/
                                               # from the jobs repo's `describe` output, then rebuild

Reads
    _store/pricing.toml     prices, the season each pass covers, the store API URL (hand-edited)
    _store/datasets.json    what the files are: datasets, columns, seasons, rows, sizes. A copy of
                            catalog.json written by `datastore_jobs.cli describe` in the jobs repo
                            ($DATASTORE_DATA_ROOT/catalog, default ~/Desktop/files/sdbs_datastore/catalog)
    _store/samples/*.csv    one small real sample per file, from the same describe run

Writes (every generated page carries a marker comment; edit this script, not the pages)
    data/index.qmd                  the store front
    data/<league>.qmd               one page per league: season pass, every completed season, the archive
    data/<league>-<dataset>.qmd     one page per dataset: facts, buy table, sample rows, column dictionary
    data/_store-head.html           store API URL + price list for scripts/data-store.js
    data/samples/*.csv              the free samples, shipped by the `resources` list in _quarto.yml
    _scripts/store/cards.tsv        share-card rows for _scripts/og-cards/build.sh

Hand-written and left alone: data/cart.qmd, thanks.qmd, library.qmd, help.qmd, data/_metadata.yml.
Standard library only (tomllib needs Python 3.11+).
"""
