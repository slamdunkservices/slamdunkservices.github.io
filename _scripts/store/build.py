def head_include(leagues: list[League], pricing: dict) -> str:
    prices = {}
    for lg in leagues:
        prices[lg.code] = {
            "name": lg.name, "current": lg.current,
            "prices": {k: v for k, v in lg.prices.items() if k != "archive"},
            "archive": lg.prices.get("archive") if lg.has_archive() else None,
            "names": {d["key"]: lg.label(d) for d in lg.datasets},
        }
    blob = json.dumps(prices, separators=(",", ":")).replace("</", "<\\/")
    return ("<!-- generated by _scripts/store/build.py; prices here are for display, checkout reprices from Stripe -->\n"
            '<meta name="sdb-store-api" content="%s">\n'
            '<script type="application/json" id="sdb-store-prices">%s</script>\n'
            '<script src="/scripts/data-store.js" defer></script>\n' % (esc(pricing["store"].get("api", "")), blob))


def cards(leagues: list[League]) -> str:
    foot = "Plain CSV · One file per season · Every column documented"
    rows = ["# slug\ttitle\tstat\tsub\tfoot  (written by _scripts/store/build.py)"]
    files = sum(lg.file_count() for lg in leagues)
    rows.append("\t".join(["data", "Sports Data, as Flat Files", "%s files · %s" % (count(files), " · ".join(lg.name for lg in leagues)),
                           "Player logs, team logs, play-by-play, results, first events", foot]))
    for lg in leagues:
        rows.append("\t".join(["data-%s" % lg.code, "%s Data" % lg.name,
                               "%s seasons · %s datasets" % (len(lg.all_seasons), len(lg.datasets)),
                               ", ".join(lg.label(d) for d in lg.datasets), foot]))
    return "\n".join(rows) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--sync", action="store_true", help="refresh _store/datasets.json and samples first")
    ap.add_argument("--catalog", default=os.environ.get(
        "DATASTORE_CATALOG", str(Path.home() / "Desktop/files/sdbs_datastore/catalog")))
    args = ap.parse_args()
    if args.sync:
        sync(Path(args.catalog).expanduser())
    pricing, catalog = load()

    leagues = []
    for code in LEAGUE_ORDER:
        if code not in pricing["leagues"]:
            continue
        if code not in catalog.get("leagues", {}):
            print("skipping %s: priced but not in datasets.json yet" % code)
            continue
        lg = League(code, pricing, catalog)
        if not lg.datasets or not lg.all_seasons:
            print("skipping %s: no files built yet" % code)
            continue
        missing = [k for k in lg.prices if k not in ("all", "archive") and k not in {d["key"] for d in lg.datasets}]
        if missing:
            print("note: %s is priced for %s but the catalog has no such dataset" % (code, ", ".join(missing)))
        wanted = (pricing["leagues"][code].get("current") or "").strip()
        if wanted and not lg.current:
            print("note: %s pass season %s has no files yet; the pass is not shown" % (code, wanted))
        leagues.append(lg)
    if not leagues:
        sys.exit("nothing to build")

    OUT.mkdir(exist_ok=True)
    keep = {"index"} | HAND_WRITTEN
    written = []
    (OUT / "index.qmd").write_text(index_page(leagues, pricing))
    for lg in leagues:
        (OUT / ("%s.qmd" % lg.code)).write_text(league_page(lg, pricing))
        keep.add(lg.code)
        for d in lg.datasets:
            (OUT / ("%s.qmd" % lg.page(d))).write_text(dataset_page(lg, d, pricing))
            keep.add(lg.page(d))
            written.append(lg.page(d))
    # A dataset that left the catalog must not leave a stale page behind.
    for path in OUT.glob("*.qmd"):
        if path.stem not in keep and MARK.split(" on ")[0] in path.read_text():
            path.unlink()
            print("removed stale %s" % path.name)

    (OUT / "_store-head.html").write_text(head_include(leagues, pricing))
    samples = OUT / "samples"
    if samples.exists():
        shutil.rmtree(samples)
    samples.mkdir()
    for path in sorted((STORE / "samples").glob("*.csv")):
        shutil.copyfile(path, samples / path.name)
    CARDS.write_text(cards(leagues))
    print("wrote index, %d league pages, %d dataset pages, %d samples"
          % (len(leagues), len(written), len(list(samples.glob("*.csv")))))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
